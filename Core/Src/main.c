  HAL_TIM_Base_Start(&htim2);

  /* Initialize Driver Abstraction Layer (DAL) wrappers */
  DAL_ADC_Init(&hadc1);
  DAL_Timer_Init(&htim1, TIM_CHANNEL_1, &htim2);
  DAL_UART_Init(&huart1);
  HAL_UART_Receive_IT(&huart1, &rx_byte, 1);

  /* Load persistent configuration from NVM flash */
  Config_Init();

  HCSR04_Init();
  ADAS_Init(&adas);
  Fault_Init(&flt);
  Buzzer_Init(&htim1, TIM_CHANNEL_1);
  AlarmManager_Init();
  EventManager_Init();
